// Lists every export the app can see from the installed Kagaz (shared + this brand's subpaths +
// tab helpers) → eslint-plugin-design-system/kagaz-exports.json. Run after every Kagaz change
// (/kagaz-upgrade, bootstrap Phase 4b): `node scripts/kagaz-exports.mjs`.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const root = process.cwd();
const require = createRequire(path.join(root, 'package.json'));
const ts = require('typescript');

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const brandName = Object.keys(pkg.dependencies ?? {}).find((d) =>
  d.startsWith('@lokal-app/kagaz-brand-'),
);
if (!brandName) throw new Error('kagaz-exports: no @lokal-app/kagaz-brand-* dependency');

function packageDir(name) {
  return path.dirname(require.resolve(`${name}/package.json`));
}

/** Export names of a package entry point, read from its published .d.ts with the TS checker. */
function exportsOf(name, subpath) {
  const dir = packageDir(name);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const entry = manifest.exports?.[subpath];
  if (!entry) return null;
  const dts = path.join(dir, typeof entry === 'string' ? entry : entry.types);
  const program = ts.createProgram([dts], {
    skipLibCheck: true,
    noEmit: true,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2022,
  });
  const checker = program.getTypeChecker();
  const symbol = checker.getSymbolAtLocation(program.getSourceFile(dts));
  return symbol
    ? checker
        .getExportsOfModule(symbol)
        .map((s) => s.getName())
        .sort()
    : [];
}

const components = '@lokal-app/kagaz-components';
const brandSubpaths = {};
for (const sub of ['./components', './icons', './geometry']) {
  const names = exportsOf(brandName, sub);
  if (names) brandSubpaths[sub.slice(2)] = names;
}
const out = {
  $comment: 'GENERATED by scripts/kagaz-exports.mjs — do not edit.',
  kagazVersion: JSON.parse(
    fs.readFileSync(path.join(packageDir(components), 'package.json'), 'utf8'),
  ).version,
  brand: brandName.replace('@lokal-app/kagaz-brand-', ''),
  brandVersion: JSON.parse(
    fs.readFileSync(path.join(packageDir(brandName), 'package.json'), 'utf8'),
  ).version,
  shared: exportsOf(components, '.'),
  navigation: exportsOf(components, './navigation'),
  brandSubpaths,
};
fs.writeFileSync(
  path.join(root, 'eslint-plugin-design-system/kagaz-exports.json'),
  JSON.stringify(out, null, 2) + '\n',
);
console.log(
  `kagaz-exports: ${out.shared.length} shared, ${out.navigation.length} navigation, ` +
    Object.entries(brandSubpaths)
      .map(([k, v]) => `${v.length} ${out.brand}/${k}`)
      .join(', '),
);
